from runtime.prediction_api.request_logger import request_logging_middleware

app.middleware("http")(request_logging_middleware)


# Model loading (cached — loaded once, reused for every request)

_loaded: tuple[object, ContractVersion] | None = None


def get_artifact() -> tuple[object, ContractVersion]:
    global _loaded
    if _loaded is not None:
        return _loaded
    model_path = Path(os.environ.get("CESAR_MODEL_PATH", ""))
    contract_path = Path(os.environ.get("CESAR_CONTRACT_PATH", ""))
    if not model_path or not contract_path:
        raise HTTPException(status_code=503, detail="CESAR_MODEL_PATH and CESAR_CONTRACT_PATH must be set")
    try:
        _loaded = load_artifact_from_path(model_path, contract_path)
        return _loaded
    except ArtifactNotFoundError as e:
        raise HTTPException(status_code=503, detail=str(e))



# Department average price per m² — used for price adequacy labels.
#
# We first try to load data-driven averages from data_enriched/department_stats.json
# (generated by the data enrichment script). If that file doesn't exist, we fall
# back to hardcoded approximate values.
#
# In production, the enrichment script should run periodically (e.g. quarterly)
# to keep these averages up to date with the latest DVF data.


# Hardcoded fallback values (approximate, from DVF open data)
_HARDCODED_DEPT_AVG: dict[str, float] = {
    "75": 10_500.0,  # Paris
    "92": 7_200.0,   # Hauts-de-Seine
    "93": 4_100.0,   # Seine-Saint-Denis
    "94": 5_800.0,   # Val-de-Marne
    "69": 3_800.0,   # Rhône
    "13": 3_200.0,   # Bouches-du-Rhône
    "06": 4_800.0,   # Alpes-Maritimes
    "33": 3_500.0,   # Gironde
    "31": 3_300.0,   # Haute-Garonne
    "44": 3_400.0,   # Loire-Atlantique
    "59": 2_500.0,   # Nord
    "67": 2_800.0,   # Bas-Rhin
    "83": 3_600.0,   # Var
    "34": 3_000.0,   # Hérault
    "38": 2_700.0,   # Isère
}


def _load_department_averages() -> dict[str, float]:
    """Load department price averages, preferring data-driven values over hardcoded ones.

    Checks for data_enriched/department_stats.json first (generated by the enrichment
    script from actual DVF data). Falls back to hardcoded values if the file doesn't
    exist or can't be parsed.
    """
    stats_path = Path("data_enriched/department_stats.json")
    if stats_path.exists():
        try:
            with open(stats_path, "r", encoding="utf-8") as f:
                stats = json.load(f)
            # Extract avg_price_per_m2 from each department entry
            data_driven = {dept: info["avg_price_per_m2"] for dept, info in stats.items()
                           if isinstance(info, dict) and "avg_price_per_m2" in info}
            if data_driven:
                return data_driven
        except (json.JSONDecodeError, OSError, KeyError):
            pass
    return _HARDCODED_DEPT_AVG.copy()


DEPT_AVG_PRICE_PER_M2 = _load_department_averages()
DEFAULT_AVG_PRICE_PER_M2 = 3_000.0


def compute_price_adequacy(
    estimated_value: float, surface_m2: float, code_departement: str
) -> tuple[float, str]:
    """Compare estimated price/m² against the department average.

    Returns (price_per_m2, label) where label is underpriced/fair/overpriced.
    Thresholds: below 0.85x average = underpriced, above 1.15x = overpriced.
    """
    if surface_m2 <= 0:
        return 0.0, "fair"

    price_per_m2 = estimated_value / surface_m2
    dept_avg = DEPT_AVG_PRICE_PER_M2.get(code_departement, DEFAULT_AVG_PRICE_PER_M2)
    ratio = price_per_m2 / dept_avg

    if ratio < 0.85:
        label = "underpriced"
    elif ratio > 1.15:
        label = "overpriced"
    else:
        label = "fair"

    return round(price_per_m2, 2), label


# Endpoints


@app.get("/health")
def health() -> JSONResponse:
    """Verify that the model is loaded and ready to serve predictions.

    Returns 200 if ready, 503 if the model or contract failed to load.
    Used by Docker healthcheck and Kubernetes readiness/liveness probes.
    """
    try:
        get_artifact()
        return JSONResponse(content={"status": "ok"})
    except HTTPException:
        return JSONResponse(
            status_code=503,
            content={"status": "error", "detail": "Model or contract not loaded"},
        )


@app.get("/model_info")
def model_info(
    artifact: Annotated[tuple[object, ContractVersion], Depends(get_artifact)],
) -> dict:
    """Return metadata about the loaded model: version, features, and target."""
    _, contract = artifact
    return {
        "model_version": contract.model_version,
        "feature_names": contract.feature_names,
        "target_name": contract.target_name,
        "type_local_categories": contract.type_local_categories,
    }


@app.post("/estimate/", response_model=EstimateResponse)
def post_estimate(
    request: EstimateRequest,
    artifact: Annotated[tuple[object, ContractVersion], Depends(get_artifact)],
) -> EstimateResponse:
    """Estimate the value of a single property and return a price adequacy label."""
    model, contract = artifact
    try:
        result = estimate_from_model(model, request, contract)

        price_per_m2, adequacy = compute_price_adequacy(
            result.estimated_value_eur,
            request.surface_reelle_bati,
            request.code_departement,
        )
        result.price_per_m2 = price_per_m2
        result.price_adequacy = adequacy

        return result
    except InvalidFeatureError as e:
        raise HTTPException(status_code=422, detail=str(e))


@app.post("/estimate/batch")
def post_estimate_batch(
    requests: list[EstimateRequest],
    artifact: Annotated[tuple[object, ContractVersion], Depends(get_artifact)],
) -> list[EstimateResponse]:
    """Estimate values for multiple properties in a single API call.

    Accepts a JSON array of property objects (max 100). Returns an array of
    estimates in the same order, each with a price adequacy label.
    """
    if len(requests) > 100:
        raise HTTPException(
            status_code=400,
            detail="Batch size limited to 100 properties per request.",
        )

    model, contract = artifact
    results: list[EstimateResponse] = []

    for req in requests:
        try:
            result = estimate_from_model(model, req, contract)

            price_per_m2, adequacy = compute_price_adequacy(
                result.estimated_value_eur,
                req.surface_reelle_bati,
                req.code_departement,
            )
            result.price_per_m2 = price_per_m2
            result.price_adequacy = adequacy
            results.append(result)

        except InvalidFeatureError as e:
            results.append(EstimateResponse(
                estimated_value_eur=0.0,
                price_per_m2=0.0,
                price_adequacy=f"error: {str(e)}",
            ))

    return results
